enum { BS_CREATE = 0, BS_CREATE_R = 1, BS_QUERY = 2, BS_QUERY_R = 3, BS_REGISTER = 4, BS_REGISTER_R = 5, BS_CALL = 8, BS_CALL_R = 9,
       BS_THREAD = 13, BS_THREAD_R = 14 };
#define OBJ_BASE 0x1000u

static uint32_t rd32(const uint8_t *p)
{
    return p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24;
}

static void wr32(uint8_t *p, uint32_t v)
{
    p[0] = v; p[1] = v >> 8; p[2] = v >> 16; p[3] = v >> 24;
}

static void ccpu_log(const SybCcpuOut *out, uint32_t unit, const char *fmt, ...)
{
    char text[200];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(text, sizeof(text), fmt, ap);
    va_end(ap);
    out->log(out->ctx, unit, text);
}

/* a GUID as Symbian/COM prints it: {xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx} from its little-endian struct */
static void guid_text(const uint8_t *g, char *buf)
{
    static const char hx[] = "0123456789abcdef";
    static const int order[16] = {3, 2, 1, 0, -1, 5, 4, -1, 7, 6, -1, 8, 9, -1, 10, 11};
    char *o = buf;
    *o++ = '{';
    for (int i = 0; i < 16; i++) {
        if (order[i] < 0) {
            *o++ = '-';
            continue;
        }
        *o++ = hx[g[order[i]] >> 4];
        *o++ = hx[g[order[i]] & 15];
    }
    for (int i = 12; i < 16; i++) {
        *o++ = hx[g[i] >> 4];
        *o++ = hx[g[i] & 15];
    }
    *o++ = '}';
    *o = 0;
}

/* a BridgeServer message { type, w1, w2, w3 } padded with zeros to CCPU_BS_REPLY, on data link `link` */
static void bs_send(const SybCcpuOut *out, uint32_t unit, uint32_t link, uint32_t type, uint32_t w1,
                    uint32_t w2, uint32_t w3)
{
    uint8_t pkt[2 + CCPU_BS_REPLY];
    memset(pkt, 0, sizeof(pkt));
    pkt[0] = link;
    wr32(pkt + 2, type);
    wr32(pkt + 6, w1);
    wr32(pkt + 10, w2);
    wr32(pkt + 14, w3);
    out->send(out->ctx, unit, pkt, sizeof(pkt));
}

/* the per-method sizes of the P1i's OPA interfaces (OpaClient.dll proxies, generated by static reading:
   docs/research/p1i-opa-methods.md): the caller tells BServer how many output bytes it expects, and BServer
   refuses a reply whose output length differs (-6), so a call is answered with exactly that many */
#include "syborg_ccpu_opa.inc"

static int opa_out_size(const uint8_t *iid, uint32_t method)
{
    for (size_t i = 0; i < sizeof(ccpu_opa_methods) / sizeof(ccpu_opa_methods[0]); i++) {
        if (ccpu_opa_methods[i].method == method && !memcmp(ccpu_opa_methods[i].iid, iid, 16)) {
            return ccpu_opa_methods[i].out;
        }
    }
    return -3;                                       /* not in the table */
}

/* fallback for an object whose IID is only guessed (an interface returned by a call: the app's class is not
   known to OpaClient, docs/research/p1i-bserver-fn3.md): the output size of this method number with this
   input length in every interface that has it, if they all agree (-3 if none or they differ) [I] */
static int opa_out_size_by_shape(uint32_t method, uint32_t inlen)
{
    int found = -3;
    for (size_t i = 0; i < sizeof(ccpu_opa_methods) / sizeof(ccpu_opa_methods[0]); i++) {
        if (ccpu_opa_methods[i].method == method && ccpu_opa_methods[i].in == (int16_t)inlen) {
            if (found != -3 && found != ccpu_opa_methods[i].out) {
                return -3;
            }
            found = ccpu_opa_methods[i].out;
        }
    }
    return found;
}

