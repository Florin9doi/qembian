static void bs_send_out(const SybCcpuOut *out, uint32_t unit, uint32_t link, uint32_t req, uint32_t outlen,
                        const uint8_t *iid, uint32_t method)
{
    uint8_t pkt[CCPU_MAX_PKT];
    uint32_t len = 16 + outlen < CCPU_BS_REPLY ? CCPU_BS_REPLY : 16 + outlen;
    memset(pkt, 0, sizeof(pkt));
    for (size_t i = 0; iid && i < sizeof(ccpu_opa_values) / sizeof(ccpu_opa_values[0]); i++) {
        if (ccpu_opa_values[i].method == method && !memcmp(ccpu_opa_values[i].iid, iid, 16) &&
            4 * ccpu_opa_values[i].word + 4 <= outlen) {
            wr32(pkt + 18 + 4 * ccpu_opa_values[i].word, ccpu_opa_values[i].value);
        }
    }
    pkt[0] = link;
    wr32(pkt + 2, BS_CALL_R);
    wr32(pkt + 6, 0);
    wr32(pkt + 10, req);
    wr32(pkt + 14, outlen);
    out->send(out->ctx, unit, pkt, 2 + len);
}

