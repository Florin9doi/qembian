static SybCcpuCreate *create_slot(SybCcpu *c)
{
    for (int i = 0; i < CCPU_CREATES; i++) {
        if (!c->create[i].used) {
            return &c->create[i];
        }
    }
    return NULL;
}

/* our request 4 { 4, app proxy P, req', 1, IID, obj }: BServer makes a proxy for obj and answers 5 */
static void bs_register_object(const SybCcpuOut *out, uint32_t unit, uint32_t link, uint32_t proxy,
                               uint32_t our_req, const uint8_t *iid, uint32_t object)
{
    uint8_t pkt[2 + 36];
    memset(pkt, 0, sizeof(pkt));
    pkt[0] = link;
    wr32(pkt + 2, BS_REGISTER);
    wr32(pkt + 6, proxy);
    wr32(pkt + 10, our_req);
    wr32(pkt + 14, 1);
    memcpy(pkt + 18, iid, 16);
    wr32(pkt + 34, object);
    out->send(out->ctx, unit, pkt, sizeof(pkt));
}

static void bs_create(SybCcpu *c, const SybCcpuOut *out, uint32_t unit, uint32_t link, const uint8_t *m, uint32_t n)
{
    uint32_t req = rd32(m + 8);
    char clsid[40], iid[40];
    if (n < 44) {
        ccpu_log(out, unit, "CreateInstance too short (%u bytes): no answer", (unsigned)n);
        return;
    }
    guid_text(m + 12, clsid);
    guid_text(m + 28, iid);
    SybCcpuCreate *slot = create_slot(c);
    if (!slot) {
        ccpu_log(out, unit, "CreateInstance %s: too many pending, answered 0x80000001", clsid);
        bs_send(out, unit, link, BS_CREATE_R, 0x80000001u, req, 0);
        return;
    }
    slot->used = 1;
    slot->kind = 0;
    slot->unit = unit;
    slot->link = link;
    slot->app_req = req;
    slot->our_req = c->next_req++;
    slot->object = c->next_obj++;
    if (slot->object - OBJ_BASE >= CCPU_OBJECTS) {
        ccpu_log(out, unit, "ERROR: object %u past the %u tracked objects: its calls get no outputs", (unsigned)slot->object, (unsigned)CCPU_OBJECTS);
    } else {
        memcpy(c->obj_clsid[slot->object - OBJ_BASE], m + 12, 16);
        memcpy(c->obj_iid[slot->object - OBJ_BASE], m + 28, 16);
    }
    ccpu_log(out, unit, "CreateInstance %s %s -> object %u, registering it", clsid, iid, (unsigned)slot->object);
    /* our request 4: { 4, app proxy, req', 1, IID, obj } (36 bytes, as the app's own type 4) */
    bs_register_object(out, unit, link, rd32(m + 4), slot->our_req, m + 28, slot->object);
}

/* QueryInterface {2, P, req, IID, obj} [I: 2/3 pairs like CreateInstance 0/1; seen on the P1i: IBatteryDevice
   0x1006 asked for IUsbChargingControl {85385620-...}]: every interface is there; the new interface is a new
   object, registered with BServer as for CreateInstance, then {3, status, req, proxy} */
static void bs_query(SybCcpu *c, const SybCcpuOut *out, uint32_t unit, uint32_t link, const uint8_t *m, uint32_t n)
{
    uint32_t req = rd32(m + 8);
    char iid[40];
    if (n < 32) {
        ccpu_log(out, unit, "QueryInterface too short (%u bytes): no answer", (unsigned)n);
        return;
    }
    guid_text(m + 12, iid);
    SybCcpuCreate *slot = create_slot(c);
    if (!slot) {
        bs_send(out, unit, link, BS_QUERY_R, 0x80000001u, req, 0);
        return;
    }
    slot->used = 1;
    slot->kind = 2;
    slot->unit = unit;
    slot->link = link;
    slot->app_req = req;
    slot->our_req = c->next_req++;
    slot->object = c->next_obj++;
    if (slot->object - OBJ_BASE >= CCPU_OBJECTS) {
        ccpu_log(out, unit, "ERROR: object %u past the %u tracked objects: its calls get no outputs", (unsigned)slot->object, (unsigned)CCPU_OBJECTS);
    } else {
        memcpy(c->obj_clsid[slot->object - OBJ_BASE], m + 12, 16);
        memcpy(c->obj_iid[slot->object - OBJ_BASE], m + 12, 16);
    }
    ccpu_log(out, unit, "QueryInterface object %u %s -> object %u, registering it", (unsigned)rd32(m + 28), iid,
             (unsigned)slot->object);
    bs_register_object(out, unit, link, rd32(m + 4), slot->our_req, m + 12, slot->object);
}

/* BServer's answer 5 to our request 4: the proxy exists (or not); answer the CreateInstance that needed it */
static void bs_registered(SybCcpu *c, const SybCcpuOut *out, uint32_t unit, const uint8_t *m, uint32_t n)
{
    uint32_t status = rd32(m + 4), req = rd32(m + 8), local = n >= 16 ? rd32(m + 12) : 0;
    for (int i = 0; i < CCPU_CREATES; i++) {
        SybCcpuCreate *s = &c->create[i];
        if (s->used && s->our_req == req && s->kind == 1) {
            /* the call that returns this interface: output word 0 status, word 1 the proxy key BServer binds */
            ccpu_log(out, unit, "object %u: BServer proxy %08x status %u, interface returned by the call",
                     (unsigned)s->object, (unsigned)local, (unsigned)status);
            uint8_t pkt[CCPU_MAX_PKT];
            uint32_t len = 16 + s->outlen < CCPU_BS_REPLY ? CCPU_BS_REPLY : 16 + s->outlen;
            memset(pkt, 0, sizeof(pkt));
            pkt[0] = s->link;
            wr32(pkt + 2, BS_CALL_R);
            wr32(pkt + 10, s->app_req);
            wr32(pkt + 14, s->outlen);
            wr32(pkt + 18, status ? 0x80004005u : 0);     /* E_FAIL-like negative status */
            wr32(pkt + 22, status ? 0 : local);
            out->send(out->ctx, s->unit, pkt, 2 + len);
            s->used = 0;
            return;
        }
        if (s->used && s->our_req == req) {
            ccpu_log(out, unit, "object %u: BServer proxy %08x status %u, %s answered",
                     (unsigned)s->object, (unsigned)local, (unsigned)status, s->kind == 2 ? "QueryInterface" : "CreateInstance");
            bs_send(out, s->unit, s->link, s->kind == 2 ? BS_QUERY_R : BS_CREATE_R, status, s->app_req, status ? 0 : local);
            s->used = 0;
            return;
        }
    }
    ccpu_log(out, unit, "answer 5 to unknown request %08x", (unsigned)req);
}

/* a call on one of our objects: answered success, no outputs; logged with the object's class and the args */
/* CCPU -> app events: after answering the trigger call, call the app's most recent callback object of that
   interface (BridgeServer type 8 {8, the app's session word, req, target, n, method, args}; docs/research/p1i-ccpu-callbacks.md) */
static const struct { uint8_t iid[16]; uint16_t method; uint8_t cb_iid[16]; uint32_t cb_method, nargs, args[4];
                      const char *why; } ccpu_callbacks[] = {
    /* ISimLock m5 (SIM-lock status request) -> ICBSimLockStatus {23b8d43b} m3 (a, b): SecurityApp waits for it before
       it lets start-up go on (bring-up.md item 23); (0, 0) = status OK, not locked [I meaning] */
    {{0xa5,0x50,0xe2,0xc3,0xd1,0x9e,0x43,0x29,0x83,0xe8,0x03,0x83,0xae,0xa3,0x8f,0x60}, 5,
     {0x3b,0xd4,0xb8,0x23,0x37,0x6c,0x42,0xb2,0xa0,0xa2,0x25,0xe1,0xc5,0x83,0x06,0xc3}, 3, 2, {0, 0}, "SIM lock status"},
    /* IRadioControl m4 (after m6 subscribed the app's ICBRadioControl handle) -> ICBRadioControl {fb52f7db} m3 (a, b):
       the power-mode change (Flight mode) waits for it; powerapp never signalled POWER_ALL_CLEAR_SEM and SecurityApp
       waited for that (bring-up.md item 24) [I meaning of a, b] */
    {{0x2a,0x66,0x25,0x03,0x24,0xd9,0x46,0x3b,0x9d,0xcc,0xc8,0x26,0xf3,0x1d,0x66,0xc8}, 4,
     {0xdb,0xf7,0x52,0xfb,0x4b,0xf6,0x48,0x17,0xb6,0x8e,0x64,0xfb,0xa9,0x73,0xcf,0x01}, 3, 2, {0, 0}, "radio state"},
};

static void bs_callbacks(SybCcpu *c, const SybCcpuOut *out, uint32_t link, uint32_t obj, const uint8_t *iid,
                         uint32_t method)
{
    for (size_t i = 0; i < sizeof(ccpu_callbacks) / sizeof(ccpu_callbacks[0]); i++) {
        if (ccpu_callbacks[i].method != method || memcmp(ccpu_callbacks[i].iid, iid, 16)) {
            continue;
        }
        int found = -1;
        uint32_t sub = obj - OBJ_BASE < CCPU_OBJECTS ? c->obj_cb[obj - OBJ_BASE] : 0;
        if (sub && !memcmp(c->cb[sub - 1].iid, ccpu_callbacks[i].cb_iid, 16)) {
            found = (int)sub - 1;                    /* the registration this object was given (its handle in a call) */
        }
        for (uint32_t k = 0; found < 0 && k < c->ncb; k++) {
            if (!memcmp(c->cb[k].iid, ccpu_callbacks[i].cb_iid, 16)) {
                found = (int)k;                      /* else the latest of that interface */
            }
        }
        char cbiid[40];
        guid_text(ccpu_callbacks[i].cb_iid, cbiid);
        if (found < 0) {
            ccpu_log(out, 0, "callback %s m%u (%s): no app registered one", cbiid, (unsigned)ccpu_callbacks[i].cb_method,
                     ccpu_callbacks[i].why);
            continue;
        }
        uint8_t pkt[2 + 24 + 16];
        uint32_t n = 4 + 4 * ccpu_callbacks[i].nargs, req = c->next_req++;
        memset(pkt, 0, sizeof(pkt));
        pkt[0] = link;                               /* the calls' link (type 8 both ways; on the registration's
                                                         link BServer answered garbage and crashed, 2026-11-17) */
        wr32(pkt + 2, BS_CALL);
        wr32(pkt + 6, c->cb[found].session);         /* the app's word 1 (with 0x100, our handle, BServer crashed in
                                                         RHeap::Free, 2026-11-17) */
        wr32(pkt + 10, req);
        wr32(pkt + 14, c->cb[found].target);
        wr32(pkt + 18, n);
        wr32(pkt + 22, ccpu_callbacks[i].cb_method);
        for (uint32_t a = 0; a < ccpu_callbacks[i].nargs; a++) {
            wr32(pkt + 26 + 4 * a, ccpu_callbacks[i].args[a]);
        }
        ccpu_log(out, c->cb[found].unit, "callback %s m%u (%s) to target %#x, request %#x", cbiid,
                 (unsigned)ccpu_callbacks[i].cb_method, ccpu_callbacks[i].why, (unsigned)c->cb[found].target,
                 (unsigned)req);
        out->send(out->ctx, c->cb[found].unit, pkt, 2 + 20 + n);
    }
}

static void bs_call(SybCcpu *c, const SybCcpuOut *out, uint32_t unit, uint32_t link, const uint8_t *m, uint32_t n)
{
    uint32_t req = rd32(m + 8), obj = n >= 16 ? rd32(m + 12) : 0, alen = n >= 20 ? rd32(m + 16) : 0;
    char clsid[40] = "?", args[3 * 16 + 4];
    if (obj - OBJ_BASE < CCPU_OBJECTS && obj < c->next_obj) {
        guid_text(c->obj_clsid[obj - OBJ_BASE], clsid);
    }
    int k = 0;
    for (uint32_t i = 20; i < n && i < 20 + 16; i++) {
        static const char hx[] = "0123456789abcdef";
        args[k++] = hx[m[i] >> 4];
        args[k++] = hx[m[i] & 15];
        if ((i - 20) % 4 == 3 && i + 1 < n) {
            args[k++] = ' ';
        }
    }
    args[k] = 0;
    int outlen = -3;
    if (obj - OBJ_BASE < CCPU_OBJECTS && obj < c->next_obj && n >= 24) {
        outlen = opa_out_size(c->obj_iid[obj - OBJ_BASE], rd32(m + 20));
        if (outlen == -3) {
            outlen = opa_out_size_by_shape(rd32(m + 20), alen);
            if (outlen != -3) {
                ccpu_log(out, unit, "object %u method %u: not in its interface's table, %d output bytes from the "
                         "interfaces with this method and %u input bytes", (unsigned)obj, (unsigned)rd32(m + 20),
                         outlen, (unsigned)alen);
            }
        }
    }
    if (obj - OBJ_BASE < CCPU_OBJECTS && obj < c->next_obj && n >= 28) {
        for (uint32_t k = 0; k < c->ncb; k++) {              /* a call that passes one of our callback handles */
            if (c->cb[k].value == rd32(m + 24)) {
                c->obj_cb[obj - OBJ_BASE] = (uint16_t)(k + 1);
            }
        }
    }
    if (obj - OBJ_BASE < CCPU_OBJECTS && obj < c->next_obj && n >= 28 && rd32(m + 20) == 5 &&
        !memcmp(c->obj_iid[obj - OBJ_BASE], iid_param_storage, 16)) {
        uint32_t id = rd32(m + 24) & 0xfffff, value = 0;
        for (size_t i = 0; i < sizeof(ccpu_params) / sizeof(ccpu_params[0]); i++) {
            if (ccpu_params[i].id == id) {
                value = ccpu_params[i].value;
            }
        }
        uint8_t pkt[2 + 16 + 12];
        memset(pkt, 0, sizeof(pkt));
        pkt[0] = link;
        wr32(pkt + 2, BS_CALL_R);
        wr32(pkt + 10, req);
        wr32(pkt + 14, 12);
        wr32(pkt + 22, 4);                           /* {status 0, length 4, value} */
        wr32(pkt + 26, value);
        ccpu_log(out, unit, "parameter %#x read: 4 bytes, value %u", (unsigned)id, (unsigned)value);
        out->send(out->ctx, unit, pkt, sizeof(pkt));
        return;
    }
    if (obj - OBJ_BASE < CCPU_OBJECTS && obj < c->next_obj) {
        for (size_t i = 0; i < sizeof(ccpu_opa_fail) / sizeof(ccpu_opa_fail[0]); i++) {
            if (ccpu_opa_fail[i].method == rd32(m + 20) && !memcmp(ccpu_opa_fail[i].iid, c->obj_iid[obj - OBJ_BASE], 16)) {
                uint8_t pkt[CCPU_MAX_PKT];
                uint32_t flen = outlen >= 4 && 16 + outlen <= CCPU_MAX_PKT - 2 ? (uint32_t)outlen : 12;   /* unknown size: {status, 0, 0} */
                uint32_t len = 16 + flen < CCPU_BS_REPLY ? CCPU_BS_REPLY : 16 + flen;
                memset(pkt, 0, sizeof(pkt));
                pkt[0] = link;
                wr32(pkt + 2, BS_CALL_R);
                wr32(pkt + 10, req);
                wr32(pkt + 14, flen);
                wr32(pkt + 18, ccpu_opa_fail[i].status);
                ccpu_log(out, unit, "call object %u %s method %u -> status %08x (%s)", (unsigned)obj, clsid,
                         (unsigned)rd32(m + 20), (unsigned)ccpu_opa_fail[i].status, ccpu_opa_fail[i].why);
                out->send(out->ctx, unit, pkt, 2 + len);
                return;
            }
        }
    }
    if (outlen < 0 || 16 + outlen > CCPU_MAX_PKT - 2) {
        /* unknown method or a variable output: success without outputs, as before (logged) */
        ccpu_log(out, unit, "call object %u %s args %u: %s -> 0 (output size %s)", (unsigned)obj, clsid,
                 (unsigned)alen, args, outlen == -3 ? "unknown" : "variable");
        bs_send(out, unit, link, BS_CALL_R, 0, req, 0);
        return;
    }
    const uint8_t *oif = opa_out_interface(c->obj_iid[obj - OBJ_BASE], rd32(m + 20));
    SybCcpuCreate *slot = oif && outlen >= 8 ? create_slot(c) : NULL;
    if (slot) {
        slot->used = 1;
        slot->kind = 1;
        slot->unit = unit;
        slot->link = link;
        slot->app_req = req;
        slot->outlen = (uint32_t)outlen;
        slot->our_req = c->next_req++;
        slot->object = c->next_obj++;
        if (slot->object - OBJ_BASE >= CCPU_OBJECTS) {
        ccpu_log(out, unit, "ERROR: object %u past the %u tracked objects: its calls get no outputs", (unsigned)slot->object, (unsigned)CCPU_OBJECTS);
    } else {
            memcpy(c->obj_clsid[slot->object - OBJ_BASE], oif, 16);
            memcpy(c->obj_iid[slot->object - OBJ_BASE], oif, 16);
        }
        char oiid[40];
        guid_text(oif, oiid);
        ccpu_log(out, unit, "call object %u %s args %u: %s -> returns interface %s, object %u, registering it",
                 (unsigned)obj, clsid, (unsigned)alen, args, oiid, (unsigned)slot->object);
        bs_register_object(out, unit, link, rd32(m + 4), slot->our_req, oif, slot->object);
        return;
    }
    ccpu_log(out, unit, "call object %u %s args %u: %s -> 0, %d output bytes", (unsigned)obj, clsid,
             (unsigned)alen, args, outlen);
    bs_send_out(out, unit, link, req, (uint32_t)outlen, c->obj_iid[obj - OBJ_BASE], rd32(m + 20));
    bs_callbacks(c, out, link, obj, c->obj_iid[obj - OBJ_BASE], rd32(m + 20));
}

void sybccpu_reset(SybCcpu *c)
{
    memset(c, 0, sizeof(*c));
    for (int i = 0; i < CCPU_UNITS; i++) {
        c->next_link[i] = 1;
    }
    c->next_value = 0x100;
    c->next_req = 0x40000001;
    c->next_obj = 0x1000;
}

void sybccpu_packet(SybCcpu *c, const SybCcpuOut *out, uint32_t unit, const uint8_t *p, uint32_t n)
{
    static const char secaif[] = "AT*SECAIF=";
    static const char ok[] = "\r\nOK\r\n";
    uint8_t pkt[CCPU_MAX_PKT];
    if (n < 2) {
        return;
    }
    if (p[0] == 0) {                                     /* CAIF control */
        uint8_t cmd = p[1] & 0x0f;
        if ((p[1] & 0x30) || !(cmd == 0 || cmd == 1 || cmd == 3 || cmd == 9) || n + 1 > CCPU_MAX_PKT) {
            return;
        }
        memcpy(pkt, p, n);
        pkt[1] = p[1] | 0x20;
        if (cmd == 0) {
            pkt[n++] = c->next_link[unit % CCPU_UNITS]++;   /* LINK_SETUP: the channel id */
        }
        out->send(out->ctx, unit, pkt, n);
        return;
    }
    uint32_t u = unit % CCPU_UNITS;
    if (p[1] == 1 && n > 2) {                            /* a fragment, more follows [V P1i: a 119-byte call as 102 + 17] */
        if (c->frag_len[u] && c->frag_link[u] != p[0]) {
            ccpu_log(out, unit, "fragment on link %u while link %u's message is open: dropped", (unsigned)p[0],
                     (unsigned)c->frag_link[u]);
            c->frag_len[u] = 0;
        }
        if (c->frag_len[u] + n - 2 > CCPU_MAX_MSG) {
            ccpu_log(out, unit, "message longer than %u bytes: dropped", (unsigned)CCPU_MAX_MSG);
            c->frag_len[u] = 0;
            return;
        }
        c->frag_link[u] = p[0];
        memcpy(c->frag[u] + c->frag_len[u], p + 2, n - 2);
        c->frag_len[u] += n - 2;
        return;
    }
    if (p[1] != 0) {                                     /* flow control on a data link */
        return;
    }
    if (c->frag_len[u] && c->frag_link[u] == p[0]) {     /* the last fragment: process the whole message */
        static uint8_t whole[2 + CCPU_MAX_MSG];
        uint32_t len = c->frag_len[u];
        c->frag_len[u] = 0;
        if (len + n - 2 > CCPU_MAX_MSG) {
            ccpu_log(out, unit, "message longer than %u bytes: dropped", (unsigned)CCPU_MAX_MSG);
            return;
        }
        whole[0] = p[0];
        whole[1] = 0;
        memcpy(whole + 2, c->frag[u], len);
        memcpy(whole + 2 + len, p + 2, n - 2);
        sybccpu_packet(c, out, unit, whole, 2 + len + n - 2);
        return;
    }
    if (n >= 2 + sizeof(secaif) - 1 && memcmp(p + 2, secaif, sizeof(secaif) - 1) == 0) {
        pkt[0] = p[0];
        pkt[1] = 0;
        memcpy(pkt + 2, ok, sizeof(ok) - 1);
        out->send(out->ctx, unit, pkt, 2 + sizeof(ok) - 1);
        return;
    }
    const uint8_t *m = p + 2;
    uint32_t mn = n - 2;
    if (mn < 12) {
        return;
    }
    uint32_t type = rd32(m), req = rd32(m + 8);
    switch (type) {
    case BS_THREAD:
        bs_send(out, unit, p[0], BS_THREAD_R, 0, req, 0);
        return;
    case BS_REGISTER:
        if (mn >= 36) {                              /* {4, w1, req, 1, iid[16], target} */
            uint32_t i = c->ncb < CCPU_CALLBACKS ? c->ncb++ : CCPU_CALLBACKS - 1;
            memcpy(c->cb[i].iid, m + 16, 16);
            c->cb[i].unit = unit;
            c->cb[i].link = p[0];
            c->cb[i].session = rd32(m + 4);
            c->cb[i].target = rd32(m + 32);
            c->cb[i].value = c->next_value;
        }
        bs_send(out, unit, p[0], BS_REGISTER_R, 0, req, c->next_value++);
        return;
    case BS_CALL_R:                                  /* the app's answer to our callback: {9, status, req, outlen} */
        ccpu_log(out, unit, "callback request %#x answered, status %u", (unsigned)req, (unsigned)rd32(m + 4));
        return;
    case BS_CREATE:
        bs_create(c, out, unit, p[0], m, mn);
        return;
    case BS_QUERY:
        bs_query(c, out, unit, p[0], m, mn);
        return;
    case BS_REGISTER_R:
        bs_registered(c, out, unit, m, mn);
        return;
    case BS_CALL:
        bs_call(c, out, unit, p[0], m, mn);
        return;
    }
    ccpu_log(out, unit, "link %u BridgeServer message type %u (not answered)", (unsigned)p[0], (unsigned)type);
}
