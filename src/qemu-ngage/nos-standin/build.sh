#!/usr/bin/env bash
# Assemble the NOS stand-in stubs and write each as a C array for the ngage board.
#   src/qemu-ngage/nos-standin/build.sh
# Needs arm-none-symbianelf binutils (~/gcc-builds/gcc-14.2.0/bin or $PATH); the generated
# headers are committed, so building QEMU does not need them.
#   nos_standin.S       -> ../hw/arm/ngage_nos_stub.h        (N-Gage QD, -M ngageqd)
#   nos_standin.S (NEM-4) -> ../hw/arm/ngage_nem4_nos_stub.h (N-Gage, -M ngage)
#   nos_standin_nhl10.S -> ../hw/arm/ngage_nhl10_nos_stub.h  (Nokia 6600, -M nokia6600)
#   nos_standin.S (NHL2) -> ../hw/arm/ngage_nhl2_nos_stub.h  (Nokia 7650, -M nokia7650)
#   nos_standin.S (NHL-8) -> ../hw/arm/ngage_nhl8_nos_stub.h  (Nokia 3650, -M nokia3650)
#   nos_standin.S (NHL-8X) -> ../hw/arm/ngage_nhl8x_nos_stub.h (Nokia 3660, -M nokia3660)
#   nos_standin_nhl10.S (RM-51) -> ../hw/arm/ngage_rm51_nos_stub.h (Nokia 3230, -M nokia3230)
#   doc_standin_ra2.S    -> ../hw/arm/ngage_ra2_doc_stub.h   (Nokia 9500 TrueFFS stand-in, -M nokia9500)
#   doc_standin_p910.S   -> ../hw/arm/ngage_p910_doc_stub.h  (P910i TrueFFS dispatcher stand-in, -M p910i)
#   doc_standin_ra2.S    -> ../hw/arm/ngage_rm12_doc_stub.h  (Nokia 7710: the 9500's stand-in at its DiskOnChip.dll, -M nokia7710)
#   bal_standin_ra2.S    -> ../hw/arm/ngage_rm12_bal_stub.h  (Nokia 7710: the 9500's Bal stand-in, relocated)
#   doc_standin_rae5.S   -> ../hw/arm/ngage_rae5_doc_stub.h  (Nokia 9210i TrueFFS flCall stand-in in Medata.pdd, -M nokia9210i)
set -euo pipefail
cd "$(dirname "$0")"
T=${CROSS:-$HOME/gcc-builds/gcc-14.2.0/bin/arm-none-symbianelf-}
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT

# build SRC LOAD (NOS entry, virtual) PREFIX (C names) OUT [as options, e.g. --defsym NHL2=1]
build() {
  local src=$1 load=$2 prefix=$3 out=$4; shift 4
  "${T}as" -march=armv4t "$@" -o "$W/s.o" "$src"
  "${T}ld" -Ttext="$load" -e _start -o "$W/s.elf" "$W/s.o"
  "${T}objcopy" -O binary -j .text "$W/s.elf" "$W/s.bin"
  "${T}nm" "$W/s.elf" | awk '$2 == "T" {print $3, $1}' > "$W/syms"
  python3 - "$W/s.bin" "$load" "$W/syms" "$prefix" "$src" > "$out" <<'PY'
import sys
b = open(sys.argv[1], 'rb').read()
up, low = sys.argv[4].upper(), sys.argv[4].lower()
print('/* Generated by src/qemu-ngage/nos-standin/build.sh from %s: do not edit. */' % sys.argv[5])
print('#define %s_NOS_STUB_VA %s' % (up, sys.argv[2]))
for l in open(sys.argv[3]):
    name, addr = l.split()
    if name != '_start':
        print('#define %s_NOS_SYM_%s 0x%s' % (up, name, addr))
print('static const uint8_t %s_nos_stub[%d] = {' % (low, len(b)))
for i in range(0, len(b), 16):
    print('    ' + ', '.join('0x%02x' % x for x in b[i:i + 16]) + ',')
print('};')
PY
  echo "$(basename "$out"): $(stat -c %s "$W/s.bin") bytes at $load"
}

build nos_standin.S       0x5149e4c4 ngage       ../hw/arm/ngage_nos_stub.h
# N-Gage (NEM-4 V 4.03): the QD's stub at its NOS entry (nosstarter literal), with its own ekern addresses (the same
# 506-export numbering, ordinals 469, 394, 493, 7, 479, 64) and NOS bss, read from the ROM
build nos_standin.S       0x5149d284 ngage_nem4  ../hw/arm/ngage_nem4_nos_stub.h \
      --defsym KERN_VARIANT=0x503346b4 --defsym SET_POWER_MODEL=0x5033c8f8 \
      --defsym POWER_MODEL_CTOR=0x5033c584 --defsym KERN_ADD_DFC=0x503451f4 \
      --defsym RAM=0x8000c680 --defsym THREAD_WRITE=0x50341a90 --defsym CHANNEL_COMPLETE=0x50334fcc
build nos_standin_nhl10.S 0x52882024 ngage_nhl10 ../hw/arm/ngage_nhl10_nos_stub.h
# Nokia 3230 (RM-51 V 05.07): the 6600's stub at its NOS entry, with its ekern exports (ordinals 426, 344,
# 451, 7, 454, 93), NOS bss and enosdriver export 2 (docs/devices/nokia-3230-rm51/bring-up.md)
